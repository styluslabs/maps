package com.styluslabs.maps;

import android.app.Notification;
import android.app.NotificationChannel;
import android.app.NotificationManager;
import android.app.PendingIntent;
import android.app.Service;
import android.content.Intent;
import android.content.pm.ServiceInfo;
import android.os.Build;
import android.os.IBinder;
import android.os.Looper;
import android.util.Log;

import android.location.Location;
import android.location.LocationManager;
import android.location.LocationListener;
import android.app.Notification.Builder;
//import androidx.core.app.NotificationCompat;
//import com.styluslabs.maps.R;


public class MapsService extends Service implements LocationListener
{
  public static final String START_RECORDING = "START";
  public static final String STOP_RECORDING = "STOP";
  public static final String EXTRA_INTERVAL = "EXTRA_INTERVAL";
  public static final String EXTRA_DISTANCE = "EXTRA_DISTANCE";

  public static final int NOTIFICATION_ID = 1;
  public static final String CHANNEL_ID = "MapsService_channel";
  //private boolean isRecording = false;
  private LocationManager locationManager;
  // notification content set from native code (possibly before service is started)
  private static MapsService instance = null;
  private static String notifyText = null;
  private static long notifyStartMs = 0;

  @Override
  public void onCreate()
  {
    super.onCreate();
    locationManager = (LocationManager) getSystemService(LOCATION_SERVICE);
  }

  // GPS left on if interval < 10 sec - see Android GnssLocationProvider.java : GPS_POLLING_THRESHOLD_INTERVAL
  private void startLocationUpdates(float minInterval, float minDistance)
  {
    long intervalMsec = (long)(minInterval*1000);
    locationManager.requestLocationUpdates(LocationManager.GPS_PROVIDER, intervalMsec, minDistance, this);
    if(locationManager.getProvider("fused") != null) {
      locationManager.requestLocationUpdates("fused", intervalMsec, minDistance, this);
    //  onLocationChanged(locationManager.getLastKnownLocation("fused"));
    }
    //else
      onLocationChanged(locationManager.getLastKnownLocation(LocationManager.GPS_PROVIDER));
  }

  @Override
  public void onLocationChanged(Location loc)
  {
    if(loc == null) return;  // getLastKnownLocation() can return null
    MapsActivity.updateLocation(loc, true);
  }

  @Override
  public void onLowMemory() {
    MapsLib.onLowMemory();
  }

  @Override
  public int onStartCommand(Intent intent, int flags, int startId)
  {
    // null intent if service is restarted after process was killed; we can't record w/o the native app (which
    //  requires the activity), so just stop - recording is restored (paused) when app is next started
    String action = intent != null ? intent.getAction() : null;
    if(START_RECORDING.equals(action)) {
      synchronized(MapsService.class) {
        instance = this;
        prepareNotification();  // this calls startForeground()
      }
      startLocationUpdates(intent.getFloatExtra(EXTRA_INTERVAL, 0), intent.getFloatExtra(EXTRA_DISTANCE, 0));
    }
    else {  // STOP_RECORDING or null intent
      synchronized(MapsService.class) { instance = null; }
      stopForeground(true);
      stopSelf();  //stopSelfResult(startId);
    }
    return START_NOT_STICKY;
  }

  private void prepareNotification()
  {
    if(Build.VERSION.SDK_INT >= 26) {
      NotificationChannel serviceChannel = new NotificationChannel(
          CHANNEL_ID, "Location Service Channel", NotificationManager.IMPORTANCE_DEFAULT);
      serviceChannel.setSound(null, null);
      getSystemService(NotificationManager.class).createNotificationChannel(serviceChannel);
    }
    // type required when targeting API 34+ (also requires FOREGROUND_SERVICE_LOCATION permission)
    if(Build.VERSION.SDK_INT >= 29)
      startForeground(NOTIFICATION_ID, buildNotification(), ServiceInfo.FOREGROUND_SERVICE_TYPE_LOCATION);
    else
      startForeground(NOTIFICATION_ID, buildNotification());
  }

  // caller must hold MapsService.class lock
  private Notification buildNotification()
  {
    Intent intent = new Intent(this, MapsActivity.class);
    intent.setAction(Intent.ACTION_MAIN);
    intent.addCategory(Intent.CATEGORY_LAUNCHER);
    PendingIntent pendingIntent = PendingIntent.getActivity(this, 0, intent, PendingIntent.FLAG_IMMUTABLE);

    Notification.Builder builder = new Notification.Builder(this, CHANNEL_ID)  //NotificationCompat
        .setContentTitle("Recording track")
        .setContentText(notifyText != null ? notifyText : "Ascend Maps is recording a track")
        .setSmallIcon(R.drawable.ic_notification)  // white on transparent - generated by scripts/notification-icon.py
        .setOngoing(true)  // prevent dismissal (at least until Android 14)
        .setOnlyAlertOnce(true)  // no sound/vibration/heads-up for updates
        .setContentIntent(pendingIntent);
    if(notifyStartMs > 0) {
      // elapsed time shown by system w/o updates from us
      builder.setWhen(notifyStartMs).setShowWhen(true).setUsesChronometer(true);
    }
    return builder.build();
  }

  @Override
  public void onDestroy()
  {
    synchronized(MapsService.class) { if(instance == this) instance = null; }
    super.onDestroy();
  }

  public static synchronized boolean isRecording() { return instance != null; }

  // may be called from any thread
  public static synchronized void updateNotification(String text, long startMs)
  {
    notifyText = text;
    notifyStartMs = startMs;
    if(instance != null)
      instance.getSystemService(NotificationManager.class).notify(NOTIFICATION_ID, instance.buildNotification());
  }

  //@Nullable
  @Override
  public IBinder onBind(Intent intent) { return null; }
}
